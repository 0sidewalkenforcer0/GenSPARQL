package org.gensparql.test;

import org.apache.jena.query.ARQ;
import org.apache.jena.query.DatasetFactory;
import org.apache.jena.query.QueryExecution;
import org.apache.jena.query.ResultSetFormatter;
import org.apache.jena.rdf.model.Model;
import org.apache.jena.rdf.model.ModelFactory;
import org.apache.jena.rdf.model.Resource;
import org.apache.jena.sparql.util.Context;
import org.apache.jena.vocabulary.RDF;
import org.apache.jena.vocabulary.RDFS;
import org.gensparql.core.similarity.JaccardSimText;
import org.gensparql.engine.GenSPARQLConstants;
import org.gensparql.engine.boot.GenSPARQL;
import org.gensparql.llm.LLMProviderRegistry;
import org.gensparql.llm.provider.MockLLMProvider;
import org.gensparql.parser.GenSPARQLQueryFactory;
import org.junit.jupiter.api.BeforeAll;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;

/**
 * θ-compatibility as Section 2.2 of the paper defines it: a shared variable is compared by
 * similarity if the solution of the GENOP side binds it to a literal generated by GENOP,
 * gen(μ2), and by equality otherwise. With chained GENOPs, the output of an earlier GENOP that
 * no pattern has mapped is still a generated literal, so a later Qi that mentions it compares it
 * by similarity, at the threshold θi of the current GENOP. Before, only the outputs of the
 * current GENOP were compared by similarity, and such a query found nothing.
 */
class ChainedGenopSimilarityTest {

    private static final String PREFIXES = """
            PREFIX ex: <http://example.org/>
            PREFIX rdfs: <http://www.w3.org/2000/01/rdf-schema#>
            """;
    private static final String M = "<model:mock:test>";

    @BeforeAll
    static void init() {
        GenSPARQL.init();
    }

    private static int rows(String body, MockLLMProvider llm) {
        LLMProviderRegistry.setDefault(llm);
        Model m = ModelFactory.createDefaultModel();
        Resource arg = m.createResource("http://example.org/arg");
        Resource ba = m.createResource("http://example.org/ba");
        m.add(arg, RDF.type, m.createResource("http://example.org/Team")).add(arg, RDFS.label, "Argentina")
                .add(arg, m.createProperty("http://example.org/capital"), ba)
                .add(ba, RDFS.label, "Buenos Aires");
        Context cxt = ARQ.getContext().copy();
        cxt.set(GenSPARQLConstants.SIM_TEXT, new JaccardSimText());
        try (QueryExecution qe = GenSPARQL.createQueryExecution(
                GenSPARQLQueryFactory.create(PREFIXES + body), DatasetFactory.wrap(m), cxt)) {
            return ResultSetFormatter.consume(qe.execSelect());
        }
    }

    @Test
    void anUnmappedOutputOfAnEarlierGenopIsComparedBySimilarity() {
        // Q1 is empty, so ?x is still the generated literal "Argentina" when Q2 = { ?x ex:capital ?y }
        // is joined with the second GENOP.
        assertEquals(1, rows("SELECT * WHERE { GENOP(\"List the teams.\", (?x), " + M + ") "
                        + "GENOP(\"Capital of {?x}?\", (?y), " + M + ") ?x ex:capital ?y }",
                new MockLLMProvider().withResponse("List the teams.", "[\"Argentina\"]")
                        .withResponse("Capital of", "[\"Buenos Aires\"]")));
    }

    @Test
    void aMappedOutputOfAnEarlierGenopIsComparedByEquality() {
        // ?x a ex:Team forms Q1 and maps ?x to the IRI before the second GENOP.
        assertEquals(1, rows("SELECT * WHERE { GENOP(\"List the teams.\", (?x), " + M + ") ?x a ex:Team . "
                        + "GENOP(\"Capital of the team {?x}?\", (?y), " + M + ") ?x ex:capital ?y }",
                new MockLLMProvider().withResponse("List the teams.", "[\"Argentina\"]")
                        .withResponse("Capital of the team", "[\"Buenos Aires\"]")));
    }

    @Test
    void theEarlierOutputIsComparedAtTheThresholdOfTheCurrentGenop() {
        // "Argentina team" has the similarity 1/2 to the label Argentina.
        MockLLMProvider llm = new MockLLMProvider().withResponse("List the teams.", "[\"Argentina team\"]")
                .withResponse("Capital of", "[\"Buenos Aires\"]");
        String q = "SELECT * WHERE { GENOP(\"List the teams.\", (?x), " + M + ") "
                + "GENOP(\"Capital of {?x}?\", (?y), " + M + "%s) ?x ex:capital ?y }";
        assertEquals(0, rows(String.format(q, ""), llm));
        assertEquals(1, rows(String.format(q, ", 0.5"), llm));
    }
}
